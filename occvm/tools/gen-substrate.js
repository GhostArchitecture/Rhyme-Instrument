#!/usr/bin/env node
/* occvm/tools/gen-substrate.js — emit the material's substrate as CSS.
 *
 * OCCVM-L12 says a hex is derived, not authored. That is a claim about PROVENANCE, and provenance only
 * survives if the derived value reaches the stylesheet without passing through a hand. This writes
 * occvm/substrate.css from occvm/material.js, and `--check` fails if the committed file has drifted —
 * the same contract occvm/tools/splice-spine.js has with the parts it splices.
 *
 * WHY A GENERATED CONSTANT RATHER THAN A RUNTIME TOKEN. 2.0's finding was that the sun DROPS OUT of the
 * substrate ratio: the faces take their angles from the slab's cut geometry, not from the light. So the
 * ramp is a constant, and computing a constant once a minute in every consumer's tick would be work that
 * buys nothing and a second place for it to be wrong. The sundial keeps owning magnitude; this owns
 * structure, once, at build time.
 *
 * Usage:  node occvm/tools/gen-substrate.js [--check]
 */
"use strict";
const fs = require("fs"), path = require("path");
const M = require(path.join(__dirname, "..", "material.js"));

const OUT = path.join(__dirname, "..", "substrate.css");
const A = M.ARAGONITE;
const k = M.authoredContrast(A);
const s = M.substrate(A, k);
const f = M.faces(A);

const pct = x => (x * 100).toFixed(2) + "%";
const css = `/* GENERATED by occvm/tools/gen-substrate.js from occvm/material.js — DO NOT HAND-EDIT.
 * Regenerate with: node occvm/tools/gen-substrate.js   (CI runs it with --check)
 *
 * OCCVM-L12, the material model. ${A.name} (${A.formula}, ${A.system}, ${A.group}), seen by its specular
 * return at the cut geometry OCCVM-L2 fixes. Each face takes one principal index at the angle it presents
 * to the viewer; the sun is absent by construction and owns magnitude elsewhere.
 *
 *   front    ${String(f.front.theta).padStart(2)}deg   n=alpha ${A.ri.alpha}   R=${pct(f.front.R)}
 *   chamfer  ${String(f.chamfer.theta).padStart(2)}deg   n=beta  ${A.ri.beta}   R=${pct(f.chamfer.R)}
 *   edge     ${String(f.edge.theta).padStart(2)}deg   n=gamma ${A.ri.gamma}   R=${pct(f.edge.R)}
 *
 * body colour ${A.body} (judgment, anchored to L1's substrate floor at 2.3)
 * contrast    ${k.toFixed(4)} (judgment, derived: log ${M.AUTHORED_SPREAD} / log ${(f.edge.R / f.front.R).toFixed(3)})
 *
 * --m-sub-hi and --m-sub-lo reproduce the authored --sub-hi and --sub-lo TO THE BYTE and neither is
 * fitted; only the body colour was anchored. --m-sub is where the material and the hand disagree, by
 * 3.91 L*. At this contrast the SPREAD matches by construction and the SHAPE does not:
 *
 *   material  ${s.ratios.map(v => v.toFixed(3)).join(" : ")}
 *   authored  5.739 : 2.539 : 1.000
 *
 * which is 2.0's raw finding (9.353 : 1.732 : 1.000 before contrast) arriving on a specific pixel: the
 * material is more convex, so it spends more of the range on the edge and less on the mid-tone.
 * Adoption is per-surface under SPINE.md section 6b. */
:root {
  --m-sub-hi: ${s.hi};
  --m-sub: ${s.mid};
  --m-sub-lo: ${s.lo};
}
`;

if (process.argv.includes("--check")) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (have !== css) {
    console.error("SUBSTRATE DRIFT: occvm/substrate.css does not match what material.js derives.");
    console.error("  run: node occvm/tools/gen-substrate.js");
    process.exit(1);
  }
  console.log(`SUBSTRATE OK: ${s.hi} / ${s.mid} / ${s.lo} at contrast ${k.toFixed(4)}`);
} else {
  fs.writeFileSync(OUT, css);
  console.log(`wrote occvm/substrate.css: ${s.hi} / ${s.mid} / ${s.lo} at contrast ${k.toFixed(4)}`);
}
